-- FloodLens AI: persistent, account-scoped citizen flood reports.
-- Run once in Supabase Dashboard → SQL Editor → New query → Run.

create table if not exists public.citizen_reports (
    id bigint generated by default as identity primary key,
    report_code text not null unique,
    user_id uuid not null references auth.users(id) on delete cascade,
    location text not null check (char_length(location) between 1 and 200),
    incident_type text not null check (
        incident_type in (
            'waterlogging',
            'river_overflow',
            'urban_flooding',
            'drain_blockage',
            'road_inundation',
            'other'
        )
    ),
    severity text not null check (
        severity in ('low', 'moderate', 'high', 'very_high')
    ),
    description text not null check (char_length(description) between 1 and 800),
    created_at timestamptz not null default now()
);

create index if not exists citizen_reports_user_created_idx
    on public.citizen_reports (user_id, created_at desc);

alter table public.citizen_reports enable row level security;

grant select, insert on public.citizen_reports to authenticated;
grant usage, select on sequence public.citizen_reports_id_seq to authenticated;

drop policy if exists "Users can read their own citizen reports"
    on public.citizen_reports;
create policy "Users can read their own citizen reports"
    on public.citizen_reports
    for select
    to authenticated
    using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own citizen reports"
    on public.citizen_reports;
create policy "Users can create their own citizen reports"
    on public.citizen_reports
    for insert
    to authenticated
    with check ((select auth.uid()) = user_id);
